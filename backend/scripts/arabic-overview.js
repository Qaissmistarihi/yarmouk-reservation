const RTL = { rightToLeft: true }

function h1(t) {
  return new Paragraph({
    children: [new TextRun({ text: t, bold: true, size: 32, color: '4744e5', font: 'Cairo' })],
    heading: HeadingLevel.HEADING_1,
    alignment: AlignmentType.RIGHT,
    bidirectional: true,
    spacing: { before: 360, after: 160 },
  })
}
function h2(t) {
  return new Paragraph({
    children: [new TextRun({ text: t, bold: true, size: 26, color: '171b2a', font: 'Cairo' })],
    heading: HeadingLevel.HEADING_2,
    alignment: AlignmentType.RIGHT,
    bidirectional: true,
    spacing: { before: 240, after: 100 },
  })
}
function h3(t) {
  return new Paragraph({
    children: [new TextRun({ text: t, bold: true, size: 23, color: '4744e5', font: 'Cairo' })],
    alignment: AlignmentType.RIGHT,
    bidirectional: true,
    spacing: { before: 180, after: 80 },
  })
}
function p(t, opts = {}) {
  return new Paragraph({
    children: [new TextRun({ text: t, size: 22, font: 'Cairo', ...opts })],
    alignment: AlignmentType.RIGHT,
    bidirectional: true,
    spacing: { before: 60, after: 60 },
  })
}
function b(t) {
  return new Paragraph({
    children: [
      new TextRun({ text: '◀ ', size: 22, font: 'Cairo', color: '4744e5', bold: true }),
      new TextRun({ text: t, size: 22, font: 'Cairo' }),
    ],
    alignment: AlignmentType.RIGHT,
    bidirectional: true,
    spacing: { before: 50, after: 50 },
    indent: { right: 300 },
  })
}
function sub(t) {
  return new Paragraph({
    children: [
      new TextRun({ text: '  • ', size: 21, font: 'Cairo', color: '6161ff' }),
      new TextRun({ text: t, size: 21, font: 'Cairo' }),
    ],
    alignment: AlignmentType.RIGHT,
    bidirectional: true,
    spacing: { before: 35, after: 35 },
    indent: { right: 600 },
  })
}
function gap() { return new Paragraph({ text: '' }) }
function pb()  { return new Paragraph({ children: [new PageBreak()] }) }

function note(t) {
  return new Paragraph({
    children: [new TextRun({ text: `📝  ${t}`, size: 21, italics: true, font: 'Cairo', color: '464555' })],
    alignment: AlignmentType.RIGHT,
    bidirectional: true,
    shading: { type: ShadingType.CLEAR, fill: 'E8EAFF' },
    spacing: { before: 80, after: 80 },
    indent: { right: 200, left: 200 },
  })
}

function tbl(headers, rows, fill = '4744e5') {
  const hRow = new TableRow({
    children: headers.map(h => new TableCell({
      children: [new Paragraph({
        children: [new TextRun({ text: h, bold: true, size: 20, font: 'Cairo', color: 'FFFFFF' })],
        alignment: AlignmentType.CENTER,
      })],
      shading: { type: ShadingType.CLEAR, fill },
    })),
  })
  const bRows = rows.map(r => new TableRow({
    children: r.map((c, i) => new TableCell({
      children: [new Paragraph({
        children: [new TextRun({ text: c, size: 20, font: 'Cairo', bold: i === 0 })],
        alignment: i === 0 ? AlignmentType.RIGHT : AlignmentType.CENTER,
        bidirectional: true,
      })],
      shading: { type: ShadingType.CLEAR, fill: 'F2F3FF' },
    })),
  }))
  return new Table({ width: { size: 100, type: WidthType.PERCENTAGE }, rows: [hRow, ...bRows] })
}

